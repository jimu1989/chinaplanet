export function buildAIContextPrompt(
  context: AIContext
): string {
  return `
معلومات السياق الحالية:

نوع المستخدم: ${context.userType}
اللغة: ${context.locale}
المسار الحالي: ${context.pathname || "غير معروف"}
معرف المستخدم: ${context.userId || "غير مسجل"}
معرف الجلسة: ${context.sessionId || "غير معروف"}

تعامل مع هذه المعلومات على أنها سياق داخلي.
لا تعرض معرفات المستخدم أو الجلسة للمستخدم إلا عند الحاجة الضرورية.
`;
}

